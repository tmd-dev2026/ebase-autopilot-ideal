'use strict';
const assert = require('node:assert/strict');
const A = require('../assets/js/aftersale.js');
const V = require('../assets/js/checks.js');
const near = (a, b) => assert.ok(Math.abs(a - b) < 1e-8, `${a} != ${b}`);
for (const value of ['12345678', 'ABCD-12345', 'a'.repeat(30), ' TRACK-123 ']) assert.equal(A.tracking(value).valid, true);
for (const value of ['', null, '1234567', 'a'.repeat(31), 'TRACK 123', '追跡123456', 'ABCD_1234', '<img onerror>']) {
  assert.equal(A.tracking(value).valid, false, String(value));
  assert.ok(A.tracking(value).reason);
}
assert.equal(A.tracking(' TRACK-123 ').value, 'TRACK-123');
assert.equal(A.takeHome, V.takeHome);
near(A.takeHome(120, 6500, 7500).yen, 1822.4);
near(A.takeHome(90, 6500, 7500).yen, -2148.7);
assert.equal(A.lowConfidence(41), true);
assert.equal(A.lowConfidence(92), false);
assert.equal(A.lowConfidence(69.99), true);
assert.equal(A.lowConfidence(70), false);
assert.equal(A.lowConfidence(null), true);
const order = { id: 'o', state: '完了', gross: 100, shipping: 2000, actualShipping: 5020, cost: 9000, date: '2026-10-19', refund: 0 };
near(A.balance(order).yen, -845);
const impact = A.refundImpact(order, 100);
assert.equal(impact.yen, 15500);
assert.equal(impact.usd, 100);
near(impact.remaining, -16345);
near(impact.remainingUsd, -16345 / 155);
assert.equal(impact.loss, true);
assert.equal(A.refundImpact({ ...order, gross: 400 }, 1).loss, false);
for (const amount of [-1, 0, 101, NaN, null]) assert.equal(A.refundImpact(order, amount), null);
assert.equal(A.refundImpact({ ...order, actualShipping: null }, 10), null);
const row = { gross: 120, shipping: 6500, cost: 7500 };
assert.ok(A.offer(row, 5).takeHome.yen > 0);
assert.ok(A.offer(row, 50).takeHome.yen < 0);
near(A.offer(row, 10).takeHome.yen, V.takeHome(108, 6500, 7500).yen);
for (const n of [0, 51, null, NaN]) assert.equal(A.offer(row, n), null);
assert.equal(A.effect({ before: 100, spend: 99, sales: 1 }), '効いている');
assert.equal(A.effect({ before: 100, spend: 100, sales: 1 }), '効いている');
assert.equal(A.effect({ before: 100, spend: 100.01, sales: 1 }), '赤字になっている');
assert.equal(A.effect({ before: 100, spend: 0, sales: 0 }), 'データが少ない—');
assert.equal(A.effect({ before: null, spend: 10, sales: 1 }), 'データが少ない—');
const orders = [order, { ...order, id: 'pending', state: '発送待ち', actualShipping: 2100 }, { ...order, id: 'unknown', actualShipping: null }, { ...order, id: 'outside', date: '2026-10-18' }];
const listings = [{ ...row, state: '出品中' }, { ...row, state: '終了' }];
const report = A.reports(orders, listings);
near(report.confirmed, -845);
near(report.estimate, V.takeHome(120, 6500, 7500).yen * 0.25);
assert.equal(report.gap, 3120);
assert.equal(report.gaps.length, 3);
assert.equal(report.gaps[2].gap, null);
near(report.days.reduce((s, d) => s + d.yen, 0), report.confirmed);
near(A.reports([{ ...order, refund: 10 }], listings).confirmed, -2395);
assert.equal(A.reports([], [{ ...row, state: '出品中', cost: null }]).estimate, null);
assert.equal(A.reports([], []).confirmed, 0);
console.log('PASS aftersale: tracking boundaries, shared money formula, confidence, refund impact, offer loss, ad effect and weekly aggregation');
